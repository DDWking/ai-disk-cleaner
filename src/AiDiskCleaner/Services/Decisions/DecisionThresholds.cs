namespace AiDiskCleaner.Services;

/// <summary>
/// 所有判定阈值的**唯一出处**。
///
/// 阈值不是拍的，是**按「判错的代价」分档量出来的** —— 说「这是缓存」说错了会误导用户去删，
/// 说「别删」说错了只是少清一个东西。所以两侧刻意不对称：
/// 清理类要过门槛，'别删'类不设门槛（拒绝猜「别删」比拒绝猜「缓存」危险得多）。
///
/// 数字放在这里而不是散在各域里，是为了让「改阈值」这件事只有一处 diff，
/// 而且改完能被 <c>AiPurposeTests</c> 的闭合性断言看见。
/// </summary>
public static class DecisionThresholds
{
    /// <summary>
    /// 「这是缓存 / 临时文件 / 安装包」这类**可清理**结论的门槛。
    ///
    /// 0.60 是量出来的，不是拍的（原始曲线见 <c>AiPurposeCriteria.ThresholdFor</c>）：
    /// 14 条「错标成缓存会很危险」的真实路径（文档 / 照片 / 游戏存档 / 编辑器设置 /
    /// 邮箱 / 种子状态 / 备份 / .ssh / 桌面 / 剪辑工程）在任何阈值下全落 keep（最低 0.55），
    /// 而放宽到 0.60 能把「模糊缓存」从 8/14 救到 12/14，再往下降收益归零。
    /// </summary>
    public const double CleanKind = 0.60;

    /// <summary>
    /// 「这是用户自己的数据 / 系统目录 / 软件自己的数据 / 开发工具本体」这类**别删**结论的门槛。
    ///
    /// **0**：把一条拿不准的「别删」挡掉，界面就只剩「未识别」—— 而「未识别」在用户眼里
    /// 等于「AI 也不知道这是什么」，比一句「你的数据」危险得多。
    /// 实测证据：<c>AppData\Local\Programs</c> 猜 keep 0.39 被 0.55 挡掉 → 显示未识别 →
    /// 那可是**装软件的地方**。
    /// </summary>
    public const double KeepKind = 0.0;

    /// <summary>
    /// 「这是模型 / 游戏素材这类大件」的门槛，留在 0.75。
    /// 它不在上面那批样本里，而且那句「删了要重新下载」本身是**劝退**方向，
    /// 说错了不危险 —— 没有数据就先不动它。
    /// </summary>
    public const double ModelKind = 0.75;

    /// <summary>
    /// 重复文件「建议保留哪一个」的门槛。
    ///
    /// 比可清理类高：这条建议会直接影响用户留哪一份，说错了的代价是**删掉想留的那份**。
    /// 低于它就不给建议（界面写「AI 没把握，未给建议」），而不是硬挑一个。
    /// </summary>
    public const double DuplicateKeep = 0.75;
}
